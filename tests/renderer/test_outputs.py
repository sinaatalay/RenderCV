@pytest.mark.parametrize(("generate", "flag"), list(flags.items()))
def test_generators_respect_dont_generate_flags(
    load_cv: LoadCv,
    sample_yaml: str,
    tmp_path: pathlib.Path,
    generate: Callable[[Project], object],
    flag: str,
) -> None:
    project = load_cv(sample_yaml, **{flag: True})

    assert generate(project) is None
    assert not (tmp_path / "rendercv_output").exists()


def test_generators_use_the_output_paths(
    load_cv: LoadCv, sample_yaml: str, tmp_path: pathlib.Path
) -> None:
    project = load_cv(
        sample_yaml,
        output_folder="build",
        pdf_path="build/NAME_IN_LOWER_KEBAB_CASE-YEAR.pdf",
        markdown_path="OUTPUT_FOLDER/md/cv.md",
    )

    assert generate_pdf(project) == tmp_path / "build" / "john-doe-2025.pdf"
    assert generate_markdown(project) == tmp_path / "build" / "md" / "cv.md"
    assert generate_html(project) == tmp_path / "build" / "John_Doe_CV.html"
